#!/usr/bin/env python3
"""把 life/_src/posts/*.md 生成为 /life/ 下的静态页面。

运行：python3 life/_src/build.py
依赖：pip3 install fonttools brotli（只有更新字体时才需要）
"""
import hashlib
import html
import json
import re
import shutil
from datetime import date
from pathlib import Path

LIFE = Path(__file__).resolve().parent.parent
SRC = LIFE / "_src"
SITE = LIFE.parent
FONT_SRC = SRC / "fonts" / "LXGWWenKai-Medium.ttf"
FONT_OUT = LIFE / "fonts"
ORIGIN = "https://gamesyuan.com"
NAME = "园中小记"
TAGLINE = "写写日常，也写写想法。"
MARK = "<!-- generated by life/_src/build.py -->"
DIGITS = "〇一二三四五六七八九"


def cn_number(n):
    if n <= 10:
        return "十" if n == 10 else DIGITS[n]
    tens, ones = divmod(n, 10)
    return ("" if tens == 1 else DIGITS[tens]) + "十" + (DIGITS[ones] if ones else "")


def cn_year(y):
    return "".join(DIGITS[int(c)] for c in str(y))


def cn_date(d):
    return f"{cn_year(d.year)}年{cn_number(d.month)}月{cn_number(d.day)}日"


def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    return re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)


def render(markdown):
    """支持：## 标题、### 小标题、> 引用、- 列表、1. 列表、--- 分隔线、![说明](图片)。"""
    out = []
    for block in re.split(r"\n\s*\n", markdown.strip()):
        lines = [line.strip() for line in block.splitlines() if line.strip()]
        first = lines[0]
        image = re.fullmatch(r"!\[(.*?)\]\((\S+?)\)", first)
        if first.startswith("### "):
            out.append(f"<h3>{inline(first[4:])}</h3>")
        elif first.startswith("## "):
            out.append(f"<h2>{inline(first[3:])}</h2>")
        elif re.fullmatch(r"-{3,}", first):
            out.append("<hr>")
        elif image:
            alt, src = image.groups()
            out.append(f'<img src="{html.escape(src)}" alt="{html.escape(alt)}" loading="lazy">')
            if alt:
                out.append(f'<p class="caption">{inline(alt)}</p>')
        elif first.startswith(">"):
            body = "<br>".join(inline(line.lstrip("> ")) for line in lines)
            out.append(f"<blockquote><p>{body}</p></blockquote>")
        elif first.startswith("- "):
            items = "".join(f"<li>{inline(line[2:])}</li>" for line in lines)
            out.append(f"<ul>{items}</ul>")
        elif re.match(r"\d+\. ", first):
            items = "".join(f"<li>{inline(re.sub(r'^[0-9]+[.] ', '', line))}</li>" for line in lines)
            out.append(f"<ol>{items}</ol>")
        else:
            out.append(f"<p>{'<br>'.join(inline(line) for line in lines)}</p>")
    return "\n".join(out)


def load_posts():
    posts = []
    for path in sorted((SRC / "posts").glob("*.md")):
        raw = path.read_text(encoding="utf-8")
        match = re.match(r"---\n(.*?)\n---\n(.*)", raw, re.S)
        if not match:
            raise SystemExit(f"{path.name} 开头缺少 --- 信息区")
        meta = dict(re.findall(r"^(\w+):\s*(.*?)\s*$", match.group(1), re.M))
        if meta.get("draft") == "true":
            continue
        for key in ("title", "date"):
            if not meta.get(key):
                raise SystemExit(f"{path.name} 缺少 {key}")
        body = match.group(2)
        posts.append({
            "slug": path.stem,
            "title": meta["title"],
            "date": date.fromisoformat(meta["date"]),
            "tags": meta.get("tags", "").split(),
            "summary": meta.get("summary", ""),
            "body": body,
            "html": render(body),
            "words": len(re.findall(r"[一-鿿]", body)),
        })
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
    return posts


def head(title, description, path, font, kind="website", extra=""):
    url = ORIGIN + path
    title, description = html.escape(title), html.escape(description)
    face = ""
    if font:
        face = (f'<link rel="preload" href="/life/fonts/{font}" as="font" type="font/woff2" crossorigin>\n'
                f'<style>@font-face{{font-family:"LXGW WenKai";src:url("/life/fonts/{font}") format("woff2");'
                'font-display:swap}</style>\n')
    return f"""<!doctype html>
{MARK}
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{description}">
<link rel="canonical" href="{url}">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<meta name="theme-color" content="#FBF6EE">
<meta property="og:type" content="{kind}">
<meta property="og:site_name" content="游戏园">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{description}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{ORIGIN}/og.png">
{face}<link rel="stylesheet" href="/life/life.css">
{extra}</head>
"""


FOOT = f"""<footer class="foot"><a href="/life/">{NAME}</a> · <a href="/">游戏园</a></footer>
</div>
</body>
</html>
"""


def index_page(posts, font):
    parts = [head(f"{NAME} | 游戏园", f"{NAME}：{TAGLINE}", "/life/", font)]
    parts.append(f"""<body>
<div class="page">
<nav class="top"><a href="/">← 游戏园</a></nav>
<header class="masthead">
  <span class="seal" aria-hidden="true">记</span>
  <h1>{NAME}</h1>
  <p>{TAGLINE}</p>
</header>
<main>
""")
    year = None
    for post in posts:
        if post["date"].year != year:
            year = post["date"].year
            parts.append(f'<h2 class="year">{cn_year(year)}</h2>\n')
        summary = f"<p>{html.escape(post['summary'])}</p>" if post["summary"] else ""
        parts.append(f"""<article class="entry">
  <time datetime="{post['date'].isoformat()}">{cn_number(post['date'].month)}月{cn_number(post['date'].day)}日</time>
  <h2><a href="/life/{post['slug']}/">{html.escape(post['title'])}</a></h2>
  {summary}
</article>
""")
    if not posts:
        parts.append('<p class="empty">还没有文章。</p>\n')
    parts.append("</main>\n" + FOOT)
    return "".join(parts)


def post_page(post, newer, older, font):
    path = f"/life/{post['slug']}/"
    description = post["summary"] or re.sub(r"\s+", "", post["body"])[:80]
    data = json.dumps({
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": post["title"],
        "datePublished": post["date"].isoformat(),
        "inLanguage": "zh-CN",
        "url": ORIGIN + path,
    }, ensure_ascii=False)
    extra = f'<script type="application/ld+json">{data}</script>\n'
    meta = [f'<span><time datetime="{post["date"].isoformat()}">{cn_date(post["date"])}</time></span>']
    meta += [f"<span>{html.escape(tag)}</span>" for tag in post["tags"]]
    pager = ""
    if older:
        pager += (f'<a class="prev" href="/life/{older["slug"]}/"><small>上一篇</small>'
                  f'{html.escape(older["title"])}</a>')
    if newer:
        pager += (f'<a class="next" href="/life/{newer["slug"]}/"><small>下一篇</small>'
                  f'{html.escape(newer["title"])}</a>')
    pager = f'<nav class="pager">{pager}</nav>\n' if pager else ""
    return head(f"{post['title']} | {NAME}", description, path, font, "article", extra) + f"""<body>
<div class="page">
<nav class="top"><a href="/life/">← {NAME}</a></nav>
<article>
<header class="head">
  <h1>{html.escape(post['title'])}</h1>
  <p class="meta">{''.join(meta)}</p>
</header>
<div class="body">
{post['html']}
</div>
<p class="end"><span class="seal" aria-hidden="true">记</span></p>
</article>
{pager}""" + FOOT


def build_font(pages):
    """只保留页面用到的字，文件才小；新文章里的新字会自动加进来。"""
    existing = sorted(FONT_OUT.glob("kai-*.woff2"))
    if not FONT_SRC.exists():
        print(f"没有找到 {FONT_SRC.name}，沿用现有字体，新字会用系统楷体显示")
        return existing[-1].name if existing else None
    from fontTools import subset
    from fontTools.ttLib import TTFont

    text = "".join(pages) + "".join(chr(c) for c in range(0x20, 0x7F)) + "，。、；：？！“”‘’（）《》〈〉…—·「」『』〇"
    options = subset.Options(flavor="woff2", layout_features=["*"], desubroutinize=True)
    font = TTFont(FONT_SRC)
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    FONT_OUT.mkdir(exist_ok=True)
    tmp = FONT_OUT / "tmp.woff2"
    subset.save_font(font, tmp, options)
    digest = hashlib.sha256("".join(sorted(set(text))).encode()).hexdigest()[:10]
    name = f"kai-{digest}.woff2"
    for old in existing:
        old.unlink()
    tmp.rename(FONT_OUT / name)
    return name


def update_sitemap(posts):
    path = SITE / "sitemap.xml"
    urls = [("/life/", "weekly", "0.6")] + [(f"/life/{p['slug']}/", "monthly", "0.5") for p in posts]
    block = "<!-- life:start -->\n" + "".join(
        f"  <url>\n    <loc>{ORIGIN}{url}</loc>\n    <changefreq>{freq}</changefreq>\n"
        f"    <priority>{priority}</priority>\n  </url>\n" for url, freq, priority in urls
    ) + "  <!-- life:end -->"
    xml = path.read_text(encoding="utf-8")
    if "<!-- life:start -->" in xml:
        xml = re.sub(r"<!-- life:start -->.*?<!-- life:end -->", lambda _: block, xml, flags=re.S)
    else:
        xml = xml.replace("</urlset>", f"  {block}\n</urlset>")
    path.write_text(xml, encoding="utf-8")


def remove_stale(posts):
    keep = {p["slug"] for p in posts}
    for page in LIFE.glob("*/index.html"):
        if page.parent.name not in keep and MARK in page.read_text(encoding="utf-8"):
            shutil.rmtree(page.parent)
            print(f"已删除下线的文章 {page.parent.name}")


def main():
    posts = load_posts()

    def pages(font):
        result = {LIFE / "index.html": index_page(posts, font)}
        for i, post in enumerate(posts):
            newer = posts[i - 1] if i else None
            older = posts[i + 1] if i + 1 < len(posts) else None
            result[LIFE / post["slug"] / "index.html"] = post_page(post, newer, older, font)
        return result

    font = build_font(pages(None).values())
    for path, content in pages(font).items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(content, encoding="utf-8")
    remove_stale(posts)
    update_sitemap(posts)
    print(f"完成：{len(posts)} 篇文章，字体 {font}")


if __name__ == "__main__":
    main()
